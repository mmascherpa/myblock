#!/usr/bin/env python3
"""Build myblock.txt from the per-site rule files in rules/.

Usage:
    python3 scripts/build.py           # write myblock.txt
    python3 scripts/build.py --check   # fail if myblock.txt is stale or rules have errors

Standard library only. The output is deterministic (no timestamps), so --check
can compare it byte for byte; the Version line is a hash of the rule content.
"""
from __future__ import annotations

import hashlib
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RULES = ROOT / "rules"
OUTPUT = ROOT / "myblock.txt"

TITLE = "myblock"
DESCRIPTION = "Personal fixes for a better browsing experience in Vivaldi"
HOMEPAGE = "https://github.com/mmascherpa/myblock"

# Section order in the output; files inside each are sorted by name.
SECTIONS = ["generic", "sites"]

# Header keys that belong only to the generated file, never to sources.
RESERVED_HEADER = re.compile(r"^(\[Adblock|!\s*(Title|Version|Expires|Homepage|Description)\s*:)", re.I)
# Syntax Vivaldi doesn't run: uBO scriptlets, uBO/AdGuard procedural cosmetics, AdGuard JS/CSS injection.
UNSUPPORTED = [
    (re.compile(r"##\+js\("), "uBlock Origin scriptlet (##+js) - use an ABP snippet (#$#) instead"),
    (re.compile(r"#@?%#"), "AdGuard JS rule (#%#) is not supported"),
    (re.compile(r"#@?\$\?#|#\$#.*\{"), "AdGuard CSS injection is not supported"),
    (re.compile(r":(has-text|matches-css|xpath|upward|remove)\("), "procedural cosmetic filter is not supported"),
]
EXTENDED_CSS = re.compile(r"#\?#")
COSMETIC = re.compile(r"^(?P<domains>[^#]*)#[@?$]?#")


def lint(path: Path, lines: list[str], section: str) -> tuple[list[str], list[str]]:
    errors, warnings = [], []
    rel = path.relative_to(ROOT)
    if not lines or not lines[0].startswith("!"):
        errors.append(f"{rel}: must start with a '! Sites:' / '! Problem:' comment header")
    for n, line in enumerate(lines, 1):
        loc = f"{rel}:{n}"
        if RESERVED_HEADER.match(line):
            errors.append(f"{loc}: list header lines are generated by the build, remove: {line}")
            continue
        if not line or line.startswith("!"):
            continue
        if line != line.strip():
            errors.append(f"{loc}: leading/trailing whitespace")
        for pattern, msg in UNSUPPORTED:
            if pattern.search(line):
                errors.append(f"{loc}: {msg}: {line}")
        if EXTENDED_CSS.search(line):
            warnings.append(f"{loc}: ABP extended CSS (#?#) is ignored by Vivaldi: {line}")
        m = COSMETIC.match(line)
        if m and section == "sites" and not m.group("domains").strip():
            errors.append(f"{loc}: cosmetic rule without a domain in rules/sites/ (would apply everywhere): {line}")
    return errors, warnings


def collect() -> tuple[list[tuple[Path, list[str]]], list[str], list[str]]:
    files, errors, warnings = [], [], []
    seen: dict[str, str] = {}
    for section in SECTIONS:
        for path in sorted((RULES / section).glob("*.txt")):
            if path.name.startswith("_"):
                continue
            lines = [l.rstrip("\n").rstrip("\r") for l in path.read_text(encoding="utf-8").splitlines()]
            while lines and not lines[-1].strip():
                lines.pop()
            e, w = lint(path, lines, section)
            errors += e
            warnings += w
            for n, line in enumerate(lines, 1):
                if line and not line.startswith("!"):
                    where = f"{path.relative_to(ROOT)}:{n}"
                    if line in seen:
                        errors.append(f"{where}: duplicate of {seen[line]}: {line}")
                    else:
                        seen[line] = where
            files.append((path, lines))
    return files, errors, warnings


def render(files: list[tuple[Path, list[str]]]) -> str:
    body: list[str] = []
    for path, lines in files:
        rel = path.relative_to(RULES).as_posix()
        body += ["", f"! ===== {rel} " + "=" * max(0, 60 - len(rel)), *lines]
    body_text = "\n".join(body) + "\n"
    rules = [l for _, ls in files for l in ls if l and not l.startswith("!")]
    version = hashlib.sha256(body_text.encode()).hexdigest()[:10]
    header = [
        "[Adblock Plus 2.0]",
        f"! Title: {TITLE}",
        f"! Description: {DESCRIPTION}",
        f"! Homepage: {HOMEPAGE}",
        f"! Version: {version}",
        "! Expires: 1 day",
        f"! Rules: {len(rules)} from {len(files)} files",
        "!",
        "! GENERATED FILE - do not edit. Edit rules/ and run: python3 scripts/build.py",
    ]
    if any("#$#" in r for r in rules):
        header.append('! Contains ABP snippet rules: tick "Allow List to Use ABP Snippet Rules" in Vivaldi.')
    return "\n".join(header) + "\n" + body_text


def main() -> int:
    check = "--check" in sys.argv[1:]
    files, errors, warnings = collect()
    for w in warnings:
        print(f"warning: {w}", file=sys.stderr)
    for e in errors:
        print(f"error: {e}", file=sys.stderr)
    if errors:
        return 1
    output = render(files)
    if check:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        if current != output:
            print("error: myblock.txt is out of date - run: python3 scripts/build.py", file=sys.stderr)
            return 1
        print(f"ok: myblock.txt is up to date ({len(files)} files)")
        return 0
    OUTPUT.write_text(output, encoding="utf-8")
    print(f"wrote {OUTPUT.name} from {len(files)} files")
    return 0


if __name__ == "__main__":
    sys.exit(main())
